def is_spike_work(project: Project, item: Item) -> bool:
    """A spike exists to answer its questions, so they do not hold it or its tasks back."""
    story = project.items.get(item.parent or "") if item.level == "task" else item
    return story is not None and story.level == "story" and story.kind == "spike"


def unmet_prerequisites(project: Project, item: Item) -> List[Unmet]:
    if item.level not in WORK_LEVELS:
        return []
    unmet: List[Unmet] = []
    confirmed = project.facets.require_confirmed_delegation
    for ref in ([] if is_spike_work(project, item) else effective(project, item, "questions")):
        question = project.question_by_id.get(ref)
        if question is None:
            unmet.append(Unmet(ref, "does not exist"))
        elif question.status == "delegated" and confirmed:
            unmet.append(Unmet(ref, "is delegated and awaits confirmation"))
        elif question.status not in ("answered", "delegated"):
            unmet.append(Unmet(ref, f"is {question.status or 'without a status'}"))
    for ref in effective(project, item, "inputs"):
        entry = project.input_by_id.get(ref)
        if entry is None:
            unmet.append(Unmet(ref, "does not exist"))
        elif not entry.satisfied:
            unmet.append(Unmet(ref, f"is {entry.status or 'without a status'}"))
    for ref in effective(project, item, "blocked_by"):
        blocker = project.items.get(ref)
        if blocker is None:
            unmet.append(Unmet(ref, "does not exist"))
        elif blocker.status != "done":
            unmet.append(Unmet(ref, f"is {blocker.status or 'without a status'}"))
    return unmet


def question_blocks(project: Project, question: Question) -> List[str]:
    """What waits on a question: its Blocks field, then every item that lists it and is not the spike answering it."""
    blocks = list(question.blocks)
    for item in sorted(project.items.values(), key=lambda entry: natural_key(entry.id)):
        if question.id in item.listed("questions") and item.id not in blocks and not is_spike_work(project, item):
            blocks.append(item.id)
    return blocks


def descendants(project: Project, item: Item) -> List[Item]:
    if item.level == "story":
        return [t for t in project.items_at("task") if t.parent == item.id]
    if item.level == "epic":
        return [s for s in project.items_at("story") if s.epic == item.id]
    if item.level == "milestone":
        return [s for s in project.items_at("story") if s.milestone == item.id]
    return []


def check_fields(project: Project, item: Item) -> List[Diagnostic]:
    out: List[Diagnostic] = []
    level = item.level

    def report(line: Optional[int], code: str, message: str) -> None:
        out.append(Diagnostic(item.path, line, code, message))

    for key, entry in item.fields.items():
        levels = KEY_LEVELS.get(key)
        if levels is None:
            report(entry.line, "backlog-field", f"unknown key {key}")
        elif level not in levels:
            report(entry.line, "backlog-field", f"{key} is not allowed on a {level}")
        elif key in LIST_KEYS and not isinstance(entry.value, tuple):
            report(entry.line, "backlog-field", f"{key} must be an inline list such as [a, b]")
        elif key not in LIST_KEYS and isinstance(entry.value, tuple):
            report(entry.line, "backlog-field", f"{key} must be a single value, not a list")

    fid = item.fields.get("id")
    if fid is None:
        report(None, "backlog-id", f"the frontmatter has no id; the file name says {item.id}")
    elif fid.value != item.id:
        report(fid.line, "backlog-id", f"id {fid.value} does not match the file name prefix {item.id}")

    for key, levels in REQUIRED_FIELDS.items():
        if level in levels and (key not in item.fields or item.fields[key].value == ""):
            report(item.line(key), "backlog-field", f"{key} is required on a {level}")
    for key, domain in FIELD_DOMAINS.items():
        value = item.scalar(key)
        if value and level in KEY_LEVELS[key] and value not in domain:
            report(item.line(key), "backlog-field", f"{key} {value!r} must be one of {', '.join(domain)}")
    release = item.scalar("release")
    if level == "story" and release and release not in project.facets.releases:
        report(item.line("release"), "backlog-field",
               f"release {release!r} is not one of {', '.join(project.facets.releases)}")
    return out


def check_structure(project: Project, item: Item) -> List[Diagnostic]:
    """Hierarchy, references, replacement, labels, kind, estimate and due date."""
    out: List[Diagnostic] = []
    level = item.level

    def report(line: Optional[int], code: str, message: str) -> None:
        out.append(Diagnostic(item.path, line, code, message))

    if level == "story":
        for needed, what in ((item.milestone, "milestone"), (item.epic, "epic")):
            if needed not in project.items:
                report(None, "backlog-hierarchy", f"story {item.id} needs its {what} file {BACKLOG_DIR}/{needed}-<slug>.md")
    elif level == "task" and item.parent not in project.items:
        report(None, "backlog-hierarchy", f"task {item.id} needs its story file {BACKLOG_DIR}/{item.parent}-<slug>.md")

    targets: Dict[str, Callable[[str], bool]] = {
        "req": lambda ref: ref in project.requirement_ids,
        "questions": lambda ref: ref in project.question_by_id,
        "inputs": lambda ref: ref in project.input_by_id,
        "blocked_by": lambda ref: ref in project.items,
        "replaces": lambda ref: ref in project.items,
        "replaced_by": lambda ref: ref in project.items,
    }
    for key, exists in targets.items():
        if level not in KEY_LEVELS[key]:
            continue
        refs = item.listed(key) if key in LIST_KEYS else tuple(v for v in [item.scalar(key)] if v)
        for ref in refs:
            if not exists(ref):
                report(item.line(key), "backlog-ref", f"{key} names {ref}, which does not exist")
            elif key == "blocked_by":
                blocker = project.items[ref]
                if ref == item.id:
                    report(item.line(key), "backlog-ref", f"{item.id} cannot block itself")
                elif blocker.level not in WORK_LEVELS:
                    report(item.line(key), "backlog-ref", f"blocked_by names {ref}, a {blocker.level}; blockers are stories or tasks")
                elif blocker.status == "cancelled":
                    report(item.line(key), "backlog-ref", f"blocker {ref} is cancelled")

    replaced = project.items.get(item.scalar("replaces"))
    if replaced is not None:
        if replaced.status != "cancelled":
            report(item.line("replaces"), "backlog-replace", f"replaces {replaced.id}, which is {replaced.status}, not cancelled")
        if replaced.scalar("replaced_by") != item.id:
            report(item.line("replaces"), "backlog-replace", f"{replaced.id} must name {item.id} in replaced_by")

    labels_line = item.line("labels")
    for area in item.areas:
        if area not in project.facets.areas:
            report(labels_line, "backlog-label", f"area:{area} is not an area declared in {PROJECT_FILE}")
    if level in WORK_LEVELS:
        lane = item.scalar("lane")
        if not item.areas:
            report(labels_line, "backlog-label", f"a {level} needs at least one area:<area> label")
        if len(item.areas) > 1 and not lane:
            report(labels_line, "backlog-label", f"several areas ({', '.join(item.areas)}); set lane to the owning one")
        if lane and lane not in item.areas:
            report(item.line("lane"), "backlog-label", f"lane {lane} is not one of the item's areas")

    if level == "story":
        if "kind" in item.fields and item.scalar("kind") not in STORY_KINDS:
            report(item.line("kind"), "backlog-kind", f"kind {item.scalar('kind')!r} must be one of {', '.join(STORY_KINDS)}")
        if item.kind == "spike" and not item.listed("questions"):
            report(item.line("kind"), "backlog-kind", "a spike story lists at least one question")

    estimate = item.scalar("estimate")
    if level in WORK_LEVELS and estimate and estimate not in ESTIMATES:
        report(item.line("estimate"), "backlog-estimate", f"estimate {estimate} must be 1, 2, 3, 5 or 8")
    if level == "story" and "estimate" in item.fields:
        both = [t.id for t in descendants(project, item) if "estimate" in t.fields]
        if both:
            report(item.line("estimate"), "backlog-estimate",
                   f"the estimate sits on the story and on its tasks {', '.join(both)}; keep one")

    due = item.scalar("due")
    if "due" in item.fields:
        if not valid_date(due):
            report(item.line("due"), "backlog-due", f"due {due!r} must be a date YYYY-MM-DD")
        if not item.scalar("due_evidence"):
            report(item.line("due"), "backlog-due", "due needs due_evidence")
    return out


def body_section_problems(item: Item) -> List[Tuple[Optional[int], str]]:
    """(line, message) for each defect in a story's or task's body sections, whatever its status."""
    marks: List[Tuple[int, str]] = []  # (index into item.body, section key), in file order
    for number, line in unfenced(item.body, item.body_line):
        marks += [(number - item.body_line, match.group(1)) for match in SECTION_MARKER.finditer(line)]
    problems: List[Tuple[Optional[int], str]] = []
    for key in BODY_REQUIRED + BODY_OPTIONAL:
        at = next((index for index, (_, found) in enumerate(marks) if found == key), None)
        if at is None:
            if key in BODY_REQUIRED:
                problems.append((None, f"section {key} is missing; add the marker <!-- mirage:section {key} --> "
                                       "before its heading"))
            continue
        start = marks[at][0]
        end = marks[at + 1][0] if at + 1 < len(marks) else len(item.body)
        region = item.body[start + 1:end]
        heading = next((index for index, line in enumerate(region) if line.strip()), None)
        if heading is None or not region[heading].lstrip().startswith("#"):
            problems.append((item.body_line + start, f"section marker {key} must sit directly before its heading"))
            continue
        content = region[heading + 1:]
        if key not in BODY_REQUIRED:
            continue
        if not any(line.strip() for line in content):
            problems.append((item.body_line + start, f"section {key} is empty; write at least one line after its heading"))
        elif key == "acceptance" and not any(CHECKLIST.match(line) for _, line in unfenced(content)):
            problems.append((item.body_line + start, "section acceptance has no checklist item"))
    return problems


def check_body(item: Item) -> List[Diagnostic]:
    if item.level not in WORK_LEVELS or item.status not in BODY_STATUSES:
        return []
    return [Diagnostic(item.path, line, "backlog-section", message) for line, message in body_section_problems(item)]


def lacks_requirement(item: Item) -> bool:
    return item.level == "story" and item.kind == "feature" and not item.listed("req")


def check_status(project: Project, item: Item) -> List[Diagnostic]:
    status = item.status
    line = item.line("status")
    out: List[Diagnostic] = []

    def report(code: str, message: str) -> None:
        out.append(Diagnostic(item.path, line, code, message))

    unmet = unmet_prerequisites(project, item)
    if status == "ready":
        if unmet:
            report("backlog-ready", "status is ready but " + ", ".join(str(u) for u in unmet))
        if item.level not in WORK_LEVELS and not item.has_checklist:
            report("backlog-ready", "status is ready but the body has no checklist item")
        if lacks_requirement(item):
            report("backlog-ready", "status is ready but the feature story lists no requirement")
    elif status == "blocked" and not unmet and not item.scalar("blocked_reason"):
        report("backlog-blocked", "status is blocked but every prerequisite is met and blocked_reason is not set")
    elif status == "done":
        if not item.scalar("evidence"):
            report("backlog-done", "status is done but evidence is not set")
        open_items = [d.id for d in descendants(project, item) if d.status not in ("done", "cancelled")]
        if open_items:
            report("backlog-done", f"status is done but not every descendant is done or cancelled: {', '.join(open_items)}")
        if item.level == "story" and item.kind == "spike":
            unanswered = [ref for ref in item.listed("questions")
                          if ref in project.question_by_id and project.question_by_id[ref].status == "open"]
            if unanswered:
                report("backlog-done", f"status is done but the spike's outcome is not recorded: {', '.join(unanswered)} is still open")
    return out


def find_cycle(graph: Dict[str, List[str]]) -> Optional[List[str]]:
    visiting, finished = set(), set()
    for start in sorted(graph, key=natural_key):
        if start in finished:
            continue
        path = [start]
        stack = [iter(graph[start])]
        visiting.add(start)
        while stack:
            nxt = next(stack[-1], None)
            if nxt is None:
                finished.add(path[-1])
                visiting.discard(path.pop())
                stack.pop()
            elif nxt in visiting:
                return path[path.index(nxt):] + [nxt]
            elif nxt not in finished:
                visiting.add(nxt)
                path.append(nxt)
                stack.append(iter(graph[nxt]))
    return None


def check_cycles(project: Project) -> List[Diagnostic]:
    work = {item.id: item for item in project.items_at(*WORK_LEVELS) if item.frontmatter_ok}
    graph = {
        item_id: sorted({b for b in item.listed("blocked_by") if b in work and b != item_id}, key=natural_key)
        for item_id, item in work.items()
    }
    cycle = find_cycle(graph)
    if cycle is None:
        return []
    nodes = cycle[:-1]
    first = min(range(len(nodes)), key=lambda i: natural_key(nodes[i]))
    ordered = nodes[first:] + nodes[:first] + [nodes[first]]
    item = work[ordered[0]]
    return [Diagnostic(item.path, item.line("blocked_by"), "backlog-cycle", "blocked_by cycle: " + " -> ".join(ordered))]


def rule_backlog(project: Project) -> List[Diagnostic]:
    out: List[Diagnostic] = []
    for item in project.items_at(*LEVELS):
        if item.frontmatter_ok:
            out += check_fields(project, item) + check_structure(project, item) + check_status(project, item)
            out += check_body(item)
    return out + check_cycles(project)


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rule_sources(project: Project) -> List[Diagnostic]:
    doc = next((d for d in project.plan if d.kind.check == "sources"), None)
    if doc is None:
        return []
    sums = project.root / doc.path
    text = read_text(sums)
    if text is None:
        return []  # the docs group reports the missing list
    base = sums.parent
    out: List[Diagnostic] = []
    listed = set()
    for number, line in enumerate(text.split("\n"), 1):
        if not line.strip():
            continue
        match = SUMS_LINE.fullmatch(line)
        if not match:
            out.append(Diagnostic(doc.path, number, "sources-hash", "the line must read `<sha256>  <relative path>`"))
            continue
        digest, rel = match.group(1).lower(), match.group(2)
        listed.add(rel)
        target = base / rel
        if target.is_dir():
            out.append(Diagnostic(doc.path, number, "sources-missing", f"{rel} is listed but is a directory, not a file"))
        elif not target.is_file():
            out.append(Diagnostic(doc.path, number, "sources-missing", f"{rel} is listed but does not exist"))
        elif sha256_file(target) != digest:
            out.append(Diagnostic(doc.path, number, "sources-hash", f"{rel} does not match its listed hash"))
    for path in sorted(base.rglob("*")):
        if path.is_file() and path != sums and path.relative_to(base).as_posix() not in listed:
            out.append(Diagnostic(
                path.relative_to(project.root).as_posix(), None, "sources-unlisted",
                f"the file is not listed in {doc.path}",
            ))
    return out


INLINE_CODE = re.compile(r"(`+).+?\1")
INLINE_LINK = re.compile(r"!?\[(?:[^\]\\]|\\.)*\]\(\s*(<[^>]*>|[^)\s]+)(?:\s+(?:\"[^\"]*\"|'[^']*'))?\s*\)")
REFERENCE_DEFINITION = re.compile(r" {0,3}\[[^\]]+\]:\s*(<[^>]*>|\S+).*")
URL_SCHEME = re.compile(r"[A-Za-z][A-Za-z0-9+.-]*:")


def link_exists(root: Path, rel: str, target: str) -> bool:
    target = target.strip("<>")
    if not target or target.startswith("#") or URL_SCHEME.match(target):
        return True
    target = unquote(target.split("#", 1)[0].split("?", 1)[0])
    base = root if target.startswith("/") else (root / rel).parent
    return (base / target.lstrip("/")).exists()


def rule_links(project: Project) -> List[Diagnostic]:
    out: List[Diagnostic] = []
    for rel in scanned_files(project.root):
        for number, line in scan_lines(project.root, rel):
            text = INLINE_CODE.sub("", line)
            targets = [m.group(1) for m in INLINE_LINK.finditer(text)]
            definition = REFERENCE_DEFINITION.fullmatch(text)
            if definition:
                targets.append(definition.group(1))
            for target in targets:
                if not link_exists(project.root, rel, target):
                    out.append(Diagnostic(rel, number, "link-broken", f"the link target {target} does not exist"))
    return out


def rule_secrets(project: Project) -> List[Diagnostic]:
    out: List[Diagnostic] = []
    for rel in scanned_files(project.root) + [PROJECT_FILE]:
        text = read_text(project.root / rel) or ""
        for number, line in enumerate(text.split("\n"), 1):
            for name, pattern in SECRET_PATTERNS:
                if pattern.search(line):
                    out.append(Diagnostic(
                        rel, number, "secret",
                        f"the line matches the {name} pattern; keep the secret out of the repository "
                        "and record where it lives in docs/inputs.md",
                    ))
    return out


