def cmd_index(root: Path, args: argparse.Namespace) -> int:
    project = load_project(root)
    for rel, render in GENERATED.items():
        text = render(project)
        if read_text(root / rel) == text:
            print(f"{rel} unchanged")
        else:
            atomic_write(root / rel, text)
            print(f"{rel} written")
    return 0


