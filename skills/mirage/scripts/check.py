def parse_when(raw: object) -> When:
    if raw == "always":
        return ("always", None)
    if isinstance(raw, dict) and len(raw) == 1:
        ((form, arg),) = raw.items()
        if form == "any":
            subforms = tuple(parse_when(sub) for sub in arg)
            if any(sub[0] not in SINGLE_FORMS for sub in subforms):
                raise ValueError("any takes single-instance forms only")
            return ("any", subforms)
        if form in SINGLE_FORMS or form in PER_FORMS or form == "listed_in":
            return (form, arg)
    raise ValueError(f"unknown when form {raw!r}")


def load_catalog(path: Path) -> Catalog:
    raw = read_json(path, "catalog.json")
    try:
        docs = tuple(
            DocKind(
                id=doc["id"],
                title=doc["title"],
                path=doc["path"],
                when=parse_when(doc["when"]),
                check=doc["check"],
                sections=tuple(Section(s["key"], s["title"]) for s in doc["sections"]),
                areas=tuple(Area(a["key"], a["ask"]) for a in doc["areas"]),
                inputs=tuple(TypicalInput(i["key"], i["title"], i["kind"]) for i in doc["inputs"]),
                alt_paths=tuple(doc.get("alt_paths", ())),
            )
            for doc in raw["docs"]
        )
        return Catalog(tuple(raw["component_kinds"]), tuple(raw["flags"]), tuple(raw["lists"]), docs)
    except (KeyError, TypeError, ValueError, AttributeError) as error:
        raise UsageError(f"cannot read catalog.json: malformed entry: {error}") from None


def is_slug(value: object) -> bool:
    return isinstance(value, str) and bool(SLUG.fullmatch(value))


def load_facets(root: Path, catalog: Catalog) -> Tuple[Facets, List[Diagnostic]]:
    raw = read_json(root / PROJECT_FILE, PROJECT_FILE)
    if not isinstance(raw, dict):
        raise UsageError(f"cannot read {PROJECT_FILE}: the top level must be an object")
    problems: List[str] = []
    allowed = {"mirage_version", "name", "language", "components", "flags", "releases", "areas",
               "require_confirmed_delegation", *catalog.lists}
    problems += [f"unknown key {key}" for key in sorted(set(raw) - allowed)]

    name = raw.get("name")
    if not isinstance(name, str) or not name.strip():
        problems.append("name must be a non-empty string")
        name = ""
    for key in ("mirage_version", "language"):
        if key in raw and not isinstance(raw[key], str):
            problems.append(f"{key} must be a string")

    components: List[Component] = []
    raw_components = raw.get("components")
    if not isinstance(raw_components, list) or not raw_components:
        problems.append("components needs at least one entry")
        raw_components = raw_components if isinstance(raw_components, list) else []
    for index, entry in enumerate(raw_components):
        if not isinstance(entry, dict) or not is_slug(entry.get("id")):
            problems.append(f"components[{index}] needs an id that is a lowercase slug")
        elif entry.get("kind") not in catalog.component_kinds:
            problems.append(f"component {entry['id']} has unknown kind {entry.get('kind')!r}")
        elif any(c.id == entry["id"] for c in components):
            problems.append(f"component id {entry['id']} is used twice")
        else:
            components.append(Component(entry["id"], entry["kind"]))

    flags: Dict[str, bool] = {}
    raw_flags = raw.get("flags", {})
    if not isinstance(raw_flags, dict):
        problems.append("flags must be an object")
        raw_flags = {}
    for key, value in raw_flags.items():
        if key not in catalog.flags:
            problems.append(f"unknown flag {key}")
        elif not isinstance(value, bool):
            problems.append(f"flag {key} must be true or false")
        else:
            flags[key] = value

    lists: Dict[str, List[str]] = {}
    for key in catalog.lists:
        values = raw.get(key, [])
        if not isinstance(values, list):
            problems.append(f"{key} must be a list")
            values = []
        lists[key] = [v for v in values if is_slug(v)]
        problems += [f"{key} entry {v!r} is not a lowercase slug" for v in values if not is_slug(v)]

    releases = raw.get("releases")
    if not isinstance(releases, list) or not releases or not all(
        isinstance(r, str) and r.strip() for r in releases
    ):
        problems.append("releases must be a non-empty list of names")
        releases = [r for r in releases if isinstance(r, str) and r.strip()] if isinstance(releases, list) else []

    areas = raw.get("areas")
    if not isinstance(areas, list) or not areas or not all(is_slug(a) for a in areas):
        problems.append("areas must be a non-empty list of lowercase slugs")
        areas = [a for a in areas if is_slug(a)] if isinstance(areas, list) else []

    confirmed = raw.get("require_confirmed_delegation", False)
    if not isinstance(confirmed, bool):
        problems.append("require_confirmed_delegation must be true or false")
        confirmed = False

    facets = Facets(name, components, flags, lists, releases, areas, confirmed)
    return facets, [Diagnostic(PROJECT_FILE, None, "project-json", p) for p in problems]


def when_always(arg: object, facets: Facets) -> Optional[str]:
    return "always"


def when_component(arg: object, facets: Facets) -> Optional[str]:
    kinds = [kind for kind in arg if any(c.kind == kind for c in facets.components)]
    return "components include " + ", ".join(kinds) if kinds else None


def when_flag(arg: object, facets: Facets) -> Optional[str]:
    return f"flag {arg} is true" if facets.flags.get(arg) else None


def when_nonempty(arg: object, facets: Facets) -> Optional[str]:
    items = sorted(set(facets.lists.get(arg, [])))
    return f"{arg} includes " + ", ".join(items) if items else None


def when_any(arg: object, facets: Facets) -> Optional[str]:
    reasons = [SINGLE_FORMS[form](sub, facets) for form, sub in arg]
    return "; ".join(r for r in reasons if r) or None


def per_item(arg: object, facets: Facets) -> List[Tuple[str, str]]:
    return [(item, f"{arg} includes {item}") for item in sorted(set(facets.lists.get(arg, [])))]


def per_component(arg: object, facets: Facets) -> List[Tuple[str, str]]:
    kinds = sorted({c.kind for c in facets.components if c.kind in arg})
    return [(kind, f"components include {kind}") for kind in kinds]


SINGLE_FORMS: Dict[str, Callable[[object, Facets], Optional[str]]] = {
    "always": when_always,
    "component": when_component,
    "flag": when_flag,
    "nonempty": when_nonempty,
    "any": when_any,
}
PER_FORMS: Dict[str, Tuple[Callable[[object, Facets], List[Tuple[str, str]]], str]] = {
    "per": (per_item, "{item}"),
    "per_component": (per_component, "{kind}"),
}


def planned_path(root: Optional[Path], kind: DocKind) -> str:
    """The kind's path, or an older name for it when only that file exists."""
    if root is not None and not (root / kind.path).exists():
        for alt in kind.alt_paths:
            if (root / alt).exists():
                return alt
    return kind.path


def make_plan(catalog: Catalog, facets: Facets, root: Optional[Path] = None) -> List[PlannedDoc]:
    plan: List[PlannedDoc] = []
    for kind in catalog.docs:
        form, arg = kind.when
        if form in SINGLE_FORMS:
            reason = SINGLE_FORMS[form](arg, facets)
            if reason:
                plan.append(PlannedDoc(kind.id, kind, planned_path(root, kind), reason))
        elif form in PER_FORMS:
            expand, placeholder = PER_FORMS[form]
            for item, reason in expand(arg, facets):
                plan.append(PlannedDoc(f"{kind.id}:{item}", kind, kind.path.replace(placeholder, item), reason))
    return plan


def listed_instances(project: Project) -> List[Tuple[DocKind, str]]:
    """Files that are instances of a `listed_in` kind: every Markdown file under its path prefix."""
    found: List[Tuple[DocKind, str]] = []
    for kind in project.catalog.docs:
        if kind.when[0] != "listed_in":
            continue
        folder = project.root / kind.path.split("{", 1)[0]
        if folder.is_dir():
            for path in sorted(folder.rglob("*.md")):
                if path.is_file():
                    found.append((kind, path.relative_to(project.root).as_posix()))
    return found


