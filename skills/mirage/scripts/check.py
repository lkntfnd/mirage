FIELD_LINE = re.compile(r"- ([A-Za-z][A-Za-z ]*?):(?:[ \t]+(.*))?")


def parse_register(spec: RegisterSpec, text: Optional[str]) -> Tuple[list, List[Diagnostic]]:
    if text is None:
        return [], []
    heading = re.compile(rf"### ({spec.prefix}-\d{{3}}) (\S.*)")
    loose_heading = re.compile(rf"###\s+{spec.prefix}-")
    entries: list = []
    diagnostics: List[Diagnostic] = []
    first_line: Dict[str, int] = {}
    current: Optional[RegisterEntry] = None

    def report(line: int, suffix: str, message: str) -> None:
        diagnostics.append(Diagnostic(spec.path, line, f"{spec.code}-{suffix}", message))

    for number, line in unfenced(text.split("\n")):
        line = line.rstrip()
        if line.startswith("#"):
            match = heading.fullmatch(line)
            if match:
                current = spec.entry(match.group(1), match.group(2).strip(), number, {})
                if current.id in first_line:
                    report(number, "duplicate", f"{current.id} is already defined on line {first_line[current.id]}")
                else:
                    first_line[current.id] = number
                entries.append(current)
            elif loose_heading.match(line):
                report(number, "parse", f"heading must read `### {spec.prefix}-nnn <title>`")
                current = None
            elif re.match(r"#{2,3}\s", line):
                current = None
            continue
        if current is None or not line.startswith("- "):
            continue
        match = FIELD_LINE.fullmatch(line)
        if not match:
            report(number, "parse", f"a field line must read `- Key: value` with Key one of: {', '.join(spec.keys)}")
            continue
        key, value = match.group(1), (match.group(2) or "").strip()
        if key not in spec.keys:
            report(number, "field", f"{current.id} has unknown field {key}; allowed: {', '.join(spec.keys)}")
        elif key in current.fields:
            report(number, "field", f"{current.id} has field {key} twice")
        else:
            current.fields[key] = Field(value, number)
    return entries, diagnostics


def parse_prd(text: Optional[str]) -> Tuple[List[Requirement], Dict[str, int]]:
    if text is None:
        return [], {}
    requirements: List[Requirement] = []
    areas: Dict[str, int] = {}
    rows = unfenced(text.split("\n"))
    in_areas = False
    for index, (number, line) in enumerate(rows):
        marker = SECTION_MARKER.search(line)
        if marker:
            in_areas = marker.group(1) == "areas"
            continue
        cells = table_cells(line)
        if cells is None or is_separator(cells):
            continue
        first = cells[0].strip("`").strip()
        if first.startswith("REQ-"):
            padded = cells + [""] * 4
            requirements.append(Requirement(first, padded[1], padded[2], padded[3], number))
            continue
        next_cells = table_cells(rows[index + 1][1]) if index + 1 < len(rows) else None
        is_header = next_cells is not None and is_separator(next_cells)
        if in_areas and first and not is_header:
            areas.setdefault(first, number)
    return requirements, areas


def parse_quoted(text: str, start: int) -> Tuple[str, int]:
    """Parse a double-quoted string at text[start]; return its value and the index after it."""
    chars: List[str] = []
    index = start + 1
    while index < len(text):
        char = text[index]
        if char == "\\":
            if index + 1 < len(text) and text[index + 1] in "\"\\":
                chars.append(text[index + 1])
                index += 2
                continue
            raise ValueError("only \\\" and \\\\ escapes are allowed")
        if char == '"':
            return "".join(chars), index + 1
        chars.append(char)
        index += 1
    raise ValueError("unterminated quoted string")


def parse_list(text: str) -> Tuple[str, ...]:
    inner = text[1:-1].strip()
    if not inner:
        return ()
    items: List[str] = []
    index = 0
    while True:
        while index < len(inner) and inner[index] == " ":
            index += 1
        if index < len(inner) and inner[index] == '"':
            value, index = parse_quoted(inner, index)
        else:
            end = inner.find(",", index)
            end = len(inner) if end < 0 else end
            value = inner[index:end].strip()
            if not value or any(c in value for c in '"[]'):
                raise ValueError("list items must be bare words or double-quoted strings")
            index = end
        items.append(value)
        while index < len(inner) and inner[index] == " ":
            index += 1
        if index == len(inner):
            return tuple(items)
        if inner[index] != ",":
            raise ValueError("list items must be separated by commas")
        index += 1


def parse_value(raw: str) -> FmValue:
    if raw.startswith('"'):
        value, end = parse_quoted(raw, 0)
        if end != len(raw):
            raise ValueError("text follows the closing quote")
        return value
    if raw.startswith("["):
        if not raw.endswith("]"):
            raise ValueError("an inline list must end with ]")
        return parse_list(raw)
    return raw


FM_LINE = re.compile(r"([a-z_]+):(?:[ \t]+(.*))?")


def parse_frontmatter(lines: Sequence[str]) -> Tuple[Dict[str, FmField], int, List[Tuple[int, str]]]:
    """Parse the strict YAML subset. Returns fields, the body's first index, and (line, error) pairs."""
    if not lines or lines[0].rstrip() != "---":
        return {}, 0, [(1, "the file must start with a --- frontmatter line")]
    body_start = frontmatter_end(lines)
    if body_start == 0:
        return {}, 0, [(1, "the frontmatter has no closing --- line")]
    fields: Dict[str, FmField] = {}
    errors: List[Tuple[int, str]] = []
    for index in range(1, body_start - 1):
        number, line = index + 1, lines[index].rstrip()
        if not line:
            continue
        match = FM_LINE.fullmatch(line)
        if not match:
            errors.append((number, "a frontmatter line must read `key: value`"))
            continue
        key = match.group(1)
        if key in fields:
            errors.append((number, f"key {key} appears twice"))
            continue
        try:
            fields[key] = FmField(parse_value((match.group(2) or "").strip()), number)
        except ValueError as error:
            errors.append((number, f"{key}: {error}"))
    return fields, body_start, errors


def load_backlog(root: Path) -> Tuple[Dict[str, Item], List[Diagnostic]]:
    items: Dict[str, Item] = {}
    diagnostics: List[Diagnostic] = []
    folder = root / BACKLOG_DIR
    files = sorted(p for p in folder.glob("*.md") if p.is_file()) if folder.is_dir() else []
    for path in files:
        if path.name == "README.md":
            continue
        rel = f"{BACKLOG_DIR}/{path.name}"
        match = ITEM_FILENAME.fullmatch(path.name)
        if not match:
            diagnostics.append(Diagnostic(
                rel, None, "backlog-filename",
                "the file name must be <ID>-<slug>.md, such as M1-E02-S03-pay-by-card.md",
            ))
            continue
        item_id = match.group(1)
        if item_id in items:
            diagnostics.append(Diagnostic(rel, None, "backlog-id", f"{item_id} is already used by {items[item_id].path}"))
            continue
        lines = path.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n").split("\n")
        fields, body_start, errors = parse_frontmatter(lines)
        diagnostics += [Diagnostic(rel, number, "backlog-frontmatter", message) for number, message in errors]
        items[item_id] = Item(item_id, rel, fields, lines[body_start:], body_start + 1, not errors)
    return items, diagnostics


def load_project(root: Path) -> Project:
    catalog = load_catalog(catalog_path(root))
    facets, diagnostics = load_facets(root, catalog)
    questions, question_diagnostics = parse_register(QUESTIONS, read_text(root / QUESTIONS_FILE))
    inputs, input_diagnostics = parse_register(INPUTS, read_text(root / INPUTS_FILE))
    requirements, prd_areas = parse_prd(read_text(root / PRD_FILE))
    items, backlog_diagnostics = load_backlog(root)
    return Project(
        root, catalog, facets, make_plan(catalog, facets, root), questions, inputs, requirements,
        prd_areas, items, diagnostics + question_diagnostics + input_diagnostics + backlog_diagnostics,
    )


def adr_files(root: Path) -> List[Tuple[str, str]]:
    """(number, relative path) for every docs/adr/NNNN-*.md file, sorted by path."""
    folder = root / ADR_DIR
    if not folder.is_dir():
        return []
    found = [(ADR_FILE.fullmatch(p.name), p) for p in sorted(folder.iterdir()) if p.is_file()]
    return [(m.group(1), p.relative_to(root).as_posix()) for m, p in found if m]


def adr_numbers(root: Path) -> List[str]:
    return sorted({number for number, _ in adr_files(root)})


def is_generated(path: Path) -> bool:
    with open(path, encoding="utf-8", errors="replace") as stream:
        return stream.readline().startswith("<!-- mirage:generated")


def scanned_files(root: Path) -> List[str]:
    """Files the refs, links and secrets groups read. Generated files only repeat IDs from their sources."""
    candidates: List[Path] = []
    docs = root / "docs"
    if docs.is_dir():
        candidates += [p for p in docs.rglob("*.md") if not p.relative_to(root).as_posix().startswith(SOURCES_DIR + "/")]
    backlog = root / BACKLOG_DIR
    if backlog.is_dir():
        candidates += list(backlog.glob("*.md"))
    candidates += [root / name for name in ("AGENTS.md", "GLOSSARY.md", "CONTEXT.md")]
    return sorted(p.relative_to(root).as_posix() for p in candidates if p.is_file() and not is_generated(p))


def scan_lines(root: Path, rel: str) -> List[Tuple[int, str]]:
    """Lines a reference or link scan reads. Backlog frontmatter is left to the backlog group."""
    lines = (read_text(root / rel) or "").split("\n")
    start = frontmatter_end(lines) if rel.startswith(BACKLOG_DIR + "/") else 0
    return unfenced(lines[start:], start + 1)


def check_sections(rel: str, key: str, kind: DocKind, text: str) -> List[Diagnostic]:
    lines = text.split("\n")
    visible = unfenced(lines)
    out: List[Diagnostic] = []
    doc_markers = [(n, m.group(1)) for n, line in visible for m in DOC_MARKER.finditer(line)]
    own = [n for n, found in doc_markers if found == key]
    if not own:
        out.append(Diagnostic(rel, None, "doc-marker", f"missing the doc marker <!-- mirage:doc {key} -->"))
    elif len(own) > 1:
        out.append(Diagnostic(rel, own[1], "doc-marker", f"the doc marker for {key} appears {len(own)} times"))
    for number, found in doc_markers:
        if found != key:
            out.append(Diagnostic(rel, number, "doc-marker", f"the doc marker names {found}; this document is {key}"))

    positions: Dict[str, List[int]] = {}
    for index, (number, line) in enumerate(visible):
        for match in SECTION_MARKER.finditer(line):
            positions.setdefault(match.group(1), []).append(index)
    for section in kind.sections:
        found = positions.get(section.key)
        if not found:
            out.append(Diagnostic(
                rel, None, "doc-section",
                f"missing the section marker <!-- mirage:section {section.key} --> for {section.title}",
            ))
            continue
        if len(found) > 1:
            out.append(Diagnostic(rel, visible[found[1]][0], "doc-section", f"section marker {section.key} appears twice"))
        following = [line for _, line in visible[found[0] + 1:] if line.strip()]
        if not following or not following[0].lstrip().startswith("#"):
            out.append(Diagnostic(
                rel, visible[found[0]][0], "doc-section",
                f"section marker {section.key} must sit directly before its heading",
            ))

    visible_numbers = {n for n, _ in visible}
    for number, line in enumerate(lines, 1):
        braces = number in visible_numbers and "{{" in line
        if braces or TODO_MARKER in line:
            what = "a {{ placeholder" if braces else "a mirage:todo marker"
            out.append(Diagnostic(rel, number, "doc-placeholder", f"the line holds {what}; write the content or cite a question"))
    return out


def check_claude_import(root: Path) -> List[Diagnostic]:
    text = read_text(root / "CLAUDE.md")
    if text is None:
        return [Diagnostic("CLAUDE.md", None, "claude-import", "CLAUDE.md is missing; it must hold the line @AGENTS.md")]
    if "@AGENTS.md" not in text.split("\n"):
        return [Diagnostic("CLAUDE.md", None, "claude-import", "CLAUDE.md has no line that is exactly @AGENTS.md")]
    return []


def rule_docs(project: Project) -> List[Diagnostic]:
    out: List[Diagnostic] = []
    for doc in project.plan:
        if doc.kind.check == "generated":
            continue  # the index group owns generated files, present or not
        text = read_text(project.root / doc.path)
        if text is None:
            out.append(Diagnostic(
                doc.path, None, "doc-missing",
                f"{doc.kind.title} ({doc.key}) is missing; it is planned because {doc.reason}"
                + "".join(f"; {alt} is accepted too" for alt in doc.kind.alt_paths),
            ))
        elif doc.kind.check == "sections":
            out += check_sections(doc.path, doc.key, doc.kind, text)
    for kind, rel in listed_instances(project):
        out += check_sections(rel, kind.id, kind, read_text(project.root / rel) or "")
    if any(doc.kind.id == "agents" for doc in project.plan):
        out += check_claude_import(project.root)
    first: Dict[str, str] = {}
    for number, rel in adr_files(project.root):
        if number in first:
            out.append(Diagnostic(rel, None, "adr-duplicate", f"ADR number {number} is already used by {first[number]}"))
        else:
            first[number] = rel
    return out


def first_difference(actual: str, expected: str) -> int:
    old, new = actual.split("\n"), expected.split("\n")
    for number, (a, b) in enumerate(zip(old, new), 1):
        if a != b:
            return number
    return min(len(old), len(new)) + 1


def rule_index(project: Project) -> List[Diagnostic]:
    out: List[Diagnostic] = []
    for rel, render in GENERATED.items():
        actual = read_text(project.root / rel)
        expected = render(project)
        if actual is None:
            out.append(Diagnostic(rel, None, "index-stale", "the generated file is missing; run index"))
        elif actual != expected:
            out.append(Diagnostic(
                rel, first_difference(actual, expected), "index-stale",
                "the generated file differs from what index writes; run index",
            ))
    return out


def check_question(question: Question, planned_areas: set) -> List[Diagnostic]:
    out: List[Diagnostic] = []

    def report(key: str, code: str, message: str) -> None:
        out.append(Diagnostic(QUESTIONS_FILE, question.line_of(key), code, f"{question.id} {message}"))

    if "Status" not in question.fields:
        report("Status", "register-status", "has no Status; use open, answered or delegated")
    elif question.status not in QUESTION_STATUSES:
        report("Status", "register-status", f"has Status {question.status!r}; use open, answered or delegated")
    if not question.value("Recommendation"):
        report("Recommendation", "register-recommendation", "needs a non-empty Recommendation")
    if question.status in ("answered", "delegated"):
        answer = question.value("Answer")
        if not answer:
            report("Answer", "register-answer", f"is {question.status} but has no Answer")
        elif not any(valid_date(d) for d in DATE.findall(answer)):
            report("Answer", "register-answer", "has an Answer without a date YYYY-MM-DD")
    for key in question.covers:
        if key not in planned_areas:
            report("Covers", "register-covers", f"covers {key}, which is not an area of a planned document")
    return out


def check_input(entry: Input) -> List[Diagnostic]:
    out: List[Diagnostic] = []

    def report(key: str, code: str, message: str) -> None:
        out.append(Diagnostic(INPUTS_FILE, entry.line_of(key), code, f"{entry.id} {message}"))

    if entry.status not in INPUT_STATUSES:
        report("Status", "inputs-status", f"has Status {entry.status!r}; use missing, provided or not-needed")
    if entry.value("Kind") not in INPUT_KINDS:
        report("Kind", "inputs-kind", f"has Kind {entry.value('Kind')!r}; use {', '.join(INPUT_KINDS)}")
    if not entry.needed_for:
        report("Needed for", "inputs-needed-for", "needs a non-empty Needed for")
    if entry.status == "missing" and not entry.value("How to get"):
        report("How to get", "inputs-how", "is missing and needs How to get")
    if entry.status == "provided" and not entry.value("Location"):
        report("Location", "inputs-location", "is provided and needs a Location")
    if entry.status == "not-needed" and not entry.value("Reason"):
        report("Reason", "inputs-reason", "is not-needed and needs a Reason")
    return out


def rule_register(project: Project) -> List[Diagnostic]:
    planned_areas = {key for doc in project.plan for key in doc.area_keys}
    out: List[Diagnostic] = []
    for question in project.questions:
        out += check_question(question, planned_areas)
    for entry in project.inputs:
        out += check_input(entry)
    return out


def rule_prd(project: Project) -> List[Diagnostic]:
    out: List[Diagnostic] = []
    first_line: Dict[str, int] = {}
    releases = project.facets.releases
    for req in project.requirements:
        problems: List[Tuple[str, str]] = []
        if not REQ_ID.fullmatch(req.id):
            problems.append(("prd-id", f"{req.id} must read REQ-<AREA>-<NNN>, such as REQ-PAY-001"))
        elif req.id in first_line:
            problems.append(("prd-duplicate", f"{req.id} is already defined on line {first_line[req.id]}"))
        else:
            first_line[req.id] = req.line
            if req.scope not in PRD_SCOPES:
                problems.append(("prd-scope", f"{req.id} has scope {req.scope!r}; use MUST, SHOULD, MAY or OUT"))
            if not (req.release in releases or (req.scope == "OUT" and req.release == "-")):
                problems.append(("prd-release", f"{req.id} has release {req.release!r}; use one of {', '.join(releases)}"))
            if req.area not in project.prd_areas:
                problems.append(("prd-area", f"{req.id} uses area {req.area}, which the areas section does not declare"))
        out += [Diagnostic(PRD_FILE, req.line, code, message) for code, message in problems]
    return out


def reference_kinds(project: Project) -> List[Tuple[re.Pattern, Callable[[str], bool], str]]:
    adrs = set(adr_numbers(project.root))
    return [
        (re.compile(r"\bREQ-[A-Z][A-Z0-9]{1,7}-\d{3}\b"), lambda ref: ref in project.requirement_ids,
         f"is not a requirement in {PRD_FILE}"),
        (re.compile(r"\bQ-\d{3}\b"), lambda ref: ref in project.question_by_id, f"is not a question in {QUESTIONS_FILE}"),
        (re.compile(r"\bIN-\d{3}\b"), lambda ref: ref in project.input_by_id, f"is not an input in {INPUTS_FILE}"),
        (re.compile(r"\bADR-\d{4}\b"), lambda ref: ref[4:] in adrs, f"has no file {ADR_DIR}/NNNN-*.md"),
        (re.compile(r"\bM\d+-E\d{2}-S\d{2}(?:-T\d{2})?\b"), lambda ref: ref in project.items,
         f"has no file in {BACKLOG_DIR}/"),
    ]


def rule_refs(project: Project) -> List[Diagnostic]:
    kinds = reference_kinds(project)
    out: List[Diagnostic] = []
    for rel in scanned_files(project.root):
        for number, line in scan_lines(project.root, rel):
            reported = set()
            for pattern, exists, missing in kinds:
                for ref in pattern.findall(line):
                    if not exists(ref) and ref not in reported:
                        reported.add(ref)
                        out.append(Diagnostic(rel, number, "ref-missing", f"{ref} {missing}"))
    return out


def check_coverage_req(project: Project) -> List[Diagnostic]:
    out: List[Diagnostic] = []
    rank = {release: index for index, release in enumerate(project.facets.releases)}
    stories = [
        s for s in project.items_at("story")
        if s.status != "cancelled" and s.scalar("release") in rank
    ]
    for req in project.requirement_ids.values():
        if req.scope not in ("MUST", "SHOULD", "MAY") or req.release not in rank:
            continue
        if not any(req.id in s.listed("req") and rank[s.scalar("release")] <= rank[req.release] for s in stories):
            out.append(Diagnostic(
                PRD_FILE, req.line, "coverage-req",
                f"{req.id} is in no live story's req with release {req.release} or earlier",
            ))
    return out


def check_coverage_area(project: Project) -> List[Diagnostic]:
    out: List[Diagnostic] = []
    covered = {key for question in project.questions for key in question.covers}
    for doc in project.plan:
        for area in doc.kind.areas:
            key = f"{doc.key}/{area.key}"
            if key not in covered:
                out.append(Diagnostic(QUESTIONS_FILE, None, "coverage-area", f"no question covers {key}: {area.ask}"))
    return out


def rule_coverage(project: Project) -> List[Diagnostic]:
    return check_coverage_req(project) + check_coverage_area(project)


