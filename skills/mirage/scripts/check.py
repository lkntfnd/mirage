def run_check(project: Project, groups: Sequence[str]) -> List[Diagnostic]:
    found = [d for d in project.parse_diagnostics if CODES[d.code] in groups]
    for group in groups:
        if group in RULES:
            found += RULES[group](project)
    return sorted(set(found), key=Diagnostic.sort_key)


def render_docs_index(project: Project) -> str:
    out = ["<!-- mirage:generated index -->", "", f"# {project.facets.name}", "", GENERATED_NOTE]
    out += ["", "## Reading order", ""]
    out += md_table(["Key", "Document", "Path", "Exists"], [
        [doc.key, doc.kind.title, f"`{doc.path}`",
         "yes" if doc.path == DOCS_INDEX or (project.root / doc.path).exists() else "no"]
        for doc in project.plan
    ])
    questions = project.unique_questions
    out += ["", "## Open questions", ""]
    out += md_table(["ID", "Question", "Blocks"], [
        [q.id, q.title, ", ".join(question_blocks(project, q)) or "-"] for q in questions if q.status == "open"
    ])
    out += ["", "## Delegated answers awaiting confirmation", ""]
    out += md_table(["ID", "Question", "Answer"], [
        [q.id, q.title, q.value("Answer") or "-"] for q in questions if q.status == "delegated"
    ])
    out += ["", "## Missing inputs", ""]
    out += md_table(["ID", "Input", "Needed for"], [
        [i.id, i.title, ", ".join(i.needed_for) or "-"] for i in project.unique_inputs if i.status == "missing"
    ])
    counts = [
        ("Requirements", len(project.requirement_ids)),
        ("Questions", len(project.question_by_id)),
        ("Inputs", len(project.input_by_id)),
        ("ADRs", len(adr_numbers(project.root))),
    ] + [(LEVEL_PLURALS[level], len(project.items_at(level))) for level in LEVELS]
    out += ["", "## Counts", ""]
    out += md_table(["Kind", "Count"], [[name, str(count)] for name, count in counts])
    return "\n".join(out) + "\n"


def index_blockers(project: Project, item: Item) -> List[str]:
    """The item's own blockers, then every question and input it still waits on."""
    ids = list(item.listed("blocked_by"))
    for unmet in unmet_prerequisites(project, item):
        if unmet.id.startswith(("Q-", "IN-")) and unmet.id not in ids:
            ids.append(unmet.id)
    return ids


def render_backlog_index(project: Project) -> str:
    out = ["<!-- mirage:generated backlog -->", "", "# Backlog", "", GENERATED_NOTE]
    work = project.items_at(*WORK_LEVELS)
    milestones = {m.id for m in project.items_at("milestone")} | {w.milestone for w in work}
    for milestone_id in sorted(milestones, key=natural_key):
        milestone = project.items.get(milestone_id)
        out += ["", f"## {milestone_id} {milestone.title}".rstrip() if milestone else f"## {milestone_id}", ""]
        if milestone is not None:
            out += [f"Status: {milestone.status or '-'}.", ""]
        rows = sorted((w for w in work if w.milestone == milestone_id), key=lambda w: natural_key(w.id))
        out += md_table(["ID", "Title", "Status", "Lane", "Blockers"], [
            [w.id, w.title, w.status or "-", w.lane or "-", ", ".join(index_blockers(project, w)) or "-"]
            for w in rows
        ])
    out += ["", "## Epics", ""]
    out += md_table(["ID", "Title", "Status"], [[e.id, e.title, e.status or "-"] for e in project.items_at("epic")])
    return "\n".join(out) + "\n"


