@dataclass
class Item:
    id: str
    path: str
    fields: Dict[str, FmField]
    body: List[str]
    body_line: int
    frontmatter_ok: bool

    @property
    def level(self) -> str:
        return level_of(self.id) or ""

    def scalar(self, key: str) -> str:
        entry = self.fields.get(key)
        return entry.value if entry and isinstance(entry.value, str) else ""

    def listed(self, key: str) -> Tuple[str, ...]:
        entry = self.fields.get(key)
        return entry.value if entry and isinstance(entry.value, tuple) else ()

    def line(self, key: str) -> Optional[int]:
        entry = self.fields.get(key)
        return entry.line if entry else None

    @property
    def title(self) -> str:
        return self.scalar("title")

    @property
    def status(self) -> str:
        return self.scalar("status")

    @property
    def kind(self) -> str:
        return self.scalar("kind") or "feature"

    @property
    def areas(self) -> List[str]:
        found: List[str] = []
        for label in self.listed("labels"):
            if label.startswith("area:") and label[5:] not in found:
                found.append(label[5:])
        return found

    @property
    def lane(self) -> Optional[str]:
        if self.scalar("lane"):
            return self.scalar("lane")
        return self.areas[0] if len(self.areas) == 1 else None

    @property
    def estimate(self) -> Optional[int]:
        value = self.scalar("estimate")
        return int(value) if value in ESTIMATES else None

    @property
    def milestone(self) -> Optional[str]:
        return self.id.split("-")[0] if self.level in WORK_LEVELS else None

    @property
    def epic(self) -> Optional[str]:
        return self.id.split("-")[1] if self.level in WORK_LEVELS else None

    @property
    def parent(self) -> Optional[str]:
        if self.level == "story":
            return self.epic
        if self.level == "task":
            return self.id.rsplit("-", 1)[0]
        return None

    @property
    def has_checklist(self) -> bool:
        return any(CHECKLIST.match(line) for _, line in unfenced(self.body))


@dataclass
class Project:
    root: Path
    catalog: Catalog
    facets: Facets
    plan: List[PlannedDoc]
    questions: List[Question]
    inputs: List[Input]
    requirements: List[Requirement]
    prd_areas: Dict[str, int]
    items: Dict[str, Item]
    parse_diagnostics: List[Diagnostic]
    question_by_id: Dict[str, Question] = field(init=False)
    input_by_id: Dict[str, Input] = field(init=False)
    requirement_ids: Dict[str, Requirement] = field(init=False)

    def __post_init__(self) -> None:
        self.question_by_id = first_by_id(self.questions)
        self.input_by_id = first_by_id(self.inputs)
        self.requirement_ids = {}
        for req in self.requirements:
            if REQ_ID.fullmatch(req.id):
                self.requirement_ids.setdefault(req.id, req)

    @property
    def unique_questions(self) -> List[Question]:
        return [self.question_by_id[key] for key in sorted(self.question_by_id)]

    @property
    def unique_inputs(self) -> List[Input]:
        return [self.input_by_id[key] for key in sorted(self.input_by_id)]

    def items_at(self, *levels: str) -> List[Item]:
        return sorted(
            (item for item in self.items.values() if item.level in levels),
            key=lambda item: (LEVEL_RANK[item.level], natural_key(item.id)),
        )


def first_by_id(entries: Sequence[RegisterEntry]) -> dict:
    found: dict = {}
    for entry in entries:
        found.setdefault(entry.id, entry)
    return found


def level_of(item_id: str) -> Optional[str]:
    for level, pattern in ID_LEVELS:
        if pattern.fullmatch(item_id):
            return level
    return None


def natural_key(item_id: str) -> tuple:
    return (item_id[:1], tuple(int(n) for n in re.findall(r"\d+", item_id)), item_id)


def read_text(path: Path) -> Optional[str]:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except (FileNotFoundError, IsADirectoryError, NotADirectoryError):
        return None


def unfenced(lines: Sequence[str], first_line: int = 1) -> List[Tuple[int, str]]:
    """Numbered lines outside fenced code blocks, fence lines excluded."""
    kept: List[Tuple[int, str]] = []
    fence: Optional[str] = None
    for number, line in enumerate(lines, first_line):
        if fence is None:
            opening = FENCE_OPEN.match(line)
            if opening:
                fence = opening.group(1)
            else:
                kept.append((number, line))
            continue
        closing = FENCE_CLOSE.match(line)
        if closing and closing.group(1)[0] == fence[0] and len(closing.group(1)) >= len(fence):
            fence = None
    return kept


def table_cells(line: str) -> Optional[List[str]]:
    text = line.strip()
    if not text.startswith("|"):
        return None
    text = text[1:]
    if text.endswith("|") and not text.endswith("\\|"):
        text = text[:-1]
    return [cell.strip().replace("\\|", "|") for cell in re.split(r"(?<!\\)\|", text)]


def is_separator(cells: Sequence[str]) -> bool:
    return bool(cells) and all(re.fullmatch(r":?-+:?", cell) for cell in cells)


def valid_date(text: str) -> bool:
    try:
        datetime.date.fromisoformat(text)
    except ValueError:
        return False
    return bool(re.fullmatch(r"\d{4}-\d{2}-\d{2}", text))


def frontmatter_end(lines: Sequence[str]) -> int:
    """Index of the first body line, or 0 when the file has no closed frontmatter."""
    if not lines or lines[0].rstrip() != "---":
        return 0
    for index in range(1, len(lines)):
        if lines[index].rstrip() == "---":
            return index + 1
    return 0


def escape_cell(text: str) -> str:
    return text.replace("|", "\\|")


def md_table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> List[str]:
    if not rows:
        return ["None."]
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(escape_cell(cell) for cell in row) + " |" for row in rows]
    return out


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o644
    handle, temp = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temp, mode)
        os.replace(temp, path)
    except BaseException:
        try:
            os.unlink(temp)
        except FileNotFoundError:
            pass
        raise


def read_json(path: Path, label: str) -> object:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise UsageError(f"cannot read {label}: {path} does not exist") from None
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise UsageError(f"cannot read {label}: {error}") from None


